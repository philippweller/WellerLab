#!/usr/bin/env python
"""Write WIDGETS.md - every widget of the suite with its one-line purpose.

    /Applications/Orange.app/Contents/MacOS/python tools/gen_widgets_md.py

The list is read from the same widget registry Orange builds (entry point +
discovery), so it cannot drift from the code. Regenerate it whenever widgets are
added or renamed; `make widgets` does exactly that.
"""
import os
import sys

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

# needs Orange's interpreter (AnyQt/orangecanvas); re-runs itself when started with
# a plain python3, so `make widgets` works with whatever python3 is on PATH
from orange_python import reexec_if_needed          # noqa: E402

reexec_if_needed("AnyQt")

from importlib import metadata as md                 # noqa: E402

from AnyQt.QtWidgets import QApplication             # noqa: E402

app = QApplication.instance() or QApplication(sys.argv or ["gen"])

from orangecanvas.registry.qt import QtWidgetRegistry          # noqa: E402
from orangewidget.workflow.discovery import WidgetDiscovery    # noqa: E402

from wellerlab import __version__                              # noqa: E402

OUT = os.path.join(ROOT, "WIDGETS.md")

#: family key -> heading; the key is matched against the widget's module path
FAMILIES = (
    ("metabo", "Metabo statistics — feature tables (GC-IMS / GC-MS)"),
    ("plsda", "PLS-DA and OPLS-DA"),
    ("pca", "PCA"),
    ("nmr", "NMR preprocessing"),
)

eps = [e for e in md.entry_points(group="orange.widgets") if "wellerlab" in e.value]
registry = QtWidgetRegistry()
WidgetDiscovery(registry).run(eps)

buckets = {key: [] for key, _ in FAMILIES}
for widget in registry.widgets():
    # WidgetDescription.module is empty; qualified_name carries the module path
    module = (getattr(widget, "module", None)
              or getattr(widget, "qualified_name", "") or "")
    family = next((key for key, _ in FAMILIES if f".{key}." in module), "other")
    buckets.setdefault(family, []).append(widget)

lines = [
    "# WellerLab widgets",
    "",
    f"`wellerlab` {__version__} — everything lives in **one** Orange category, "
    f"**Weller Lab** ({len(registry.widgets())} widgets). Generated by "
    "`tools/gen_widgets_md.py`; do not edit by hand.",
    "",
    "Install/update through Orange's *Options → Add-ons* dialog (PyPI package "
    "`wellerlab`), or per terminal with Orange's own Python:",
    "",
    "```bash",
    "\"/Applications/Orange.app/Contents/MacOS/python\" -m pip install --no-user "
    "--upgrade --no-deps wellerlab",
    "```",
    "",
]
for key, heading in FAMILIES:
    entries = sorted(buckets.get(key, []), key=lambda w: w.name)
    if not entries:
        continue
    lines += [f"## {heading}", ""]
    for widget in entries:
        desc = " ".join((widget.description or "").split())
        lines.append(f"- **{widget.name}** — {desc}")
    lines.append("")

other = sorted(buckets.get("other", []), key=lambda w: w.name)
if other:
    lines += ["## Other", ""]
    lines += [f"- **{w.name}** — {' '.join((w.description or '').split())}"
              for w in other]
    lines.append("")

# a short "where to start" note, so the file answers the first question a user has
lines += [
    "## Typical order of use",
    "",
    "1. **Metabo Feature Table** — read a Compound Discoverer export "
    "(semicolon CSV, sample/group header rows).",
    "2. **Metabo Preprocess** — sum-normalise, log2, impute, autoscale.",
    "3. **Metabo Univariate Stats** — per-feature ANOVA / Welch / Kruskal-Wallis "
    "with BH-FDR, log2FC and group means.",
    "4. **Metabo Volcano** / **Metabo Heatmap** — visualise, click or lasso "
    "features, hand the selection on as *Selected Data* "
    "(e.g. to a Data Table or PCA Pro).",
    "5. **OPLS-DA** — two-class contrast with an interactive S-plot; pick the "
    "class pair in the *Compare* box. **PCA Pro** — scores with Hotelling T²/Q "
    "outlier diagnostics.",
    "",
    "The NMR widgets expect 1D spectra (ppm columns) and, for Peak Finding / "
    "Calibration / Peak Match, an R installation with the Rnmr1D package.",
]

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")

print(f"wrote {OUT} ({len(registry.widgets())} widgets, wellerlab {__version__})")
for key, heading in FAMILIES:
    print(f"  {key:8} {len(buckets.get(key, [])):2}  {heading}")
